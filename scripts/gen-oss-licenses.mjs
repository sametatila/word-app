import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const MOBILE = path.join(ROOT, "mobile");
const OUT = path.join(ROOT, "src", "content", "oss-licenses.json");
const PODS_ACK = path.join(MOBILE, "ios", "Pods", "Target Support Files", "Pods-Lernomi", "Pods-Lernomi-acknowledgements.markdown");

const LICENSE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "license", "license.md", "LICENSE-MIT", "COPYING", "LICENSE.MIT"];

function licenseOf(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses) && pkg.licenses[0]?.type) return pkg.licenses.map((l) => l.type).join(" OR ");
  return "UNKNOWN";
}

function repoOf(pkg) {
  const r = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  if (!r) return pkg.homepage ?? null;
  return r.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/");
}

function textOf(dir) {
  for (const f of LICENSE_FILES) {
    const p = path.join(dir, f);
    if (fs.existsSync(p) && fs.statSync(p).isFile()) return fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n").trim();
  }
  return null;
}

/** Node'un çözümleme kuralıyla paketi bul (iç içe node_modules dahil). */
function resolvePkg(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const p = path.join(dir, "node_modules", name, "package.json");
    if (fs.existsSync(p)) return p;
    const up = path.dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

const seen = new Map();
function walk(name, fromDir) {
  const pj = resolvePkg(name, fromDir);
  if (!pj) return;
  const dir = fs.realpathSync(path.dirname(pj));
  const pkg = JSON.parse(fs.readFileSync(pj, "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  seen.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), url: repoOf(pkg), text: textOf(dir) });
  for (const d of Object.keys(pkg.dependencies ?? {})) walk(d, dir);
}

const root = JSON.parse(fs.readFileSync(path.join(MOBILE, "package.json"), "utf8"));
for (const d of Object.keys(root.dependencies ?? {})) walk(d, MOBILE);
const js = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

/** CocoaPods bildirimi: "## Ad" başlıklarıyla bölünmüş markdown. */
function parsePods(md) {
  const parts = md.split(/^## /m).slice(1);
  return parts
    .map((p) => {
      const nl = p.indexOf("\n");
      return { name: p.slice(0, nl).trim(), text: p.slice(nl + 1).trim() };
    })
    .filter((p) => p.name && p.text && !/^Generated by CocoaPods/i.test(p.text))
    .sort((a, b) => a.name.localeCompare(b.name));
}
