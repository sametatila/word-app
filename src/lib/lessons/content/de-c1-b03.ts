import { de, tr, type Lesson, type LectureStep, type Segment } from "../types";

/**
 * C1 · Modül 3 — Retorik ve sunum sanatı (021–030).
 *
 * Bu modülün öğrettiği şey dilbilgisi değil MİMARİ: aynı bilgiyi taşıyan iki
 * konuşmadan birinin neden akılda kaldığı. Araçlar sayılı ve öğrenilebilir —
 * vurgu için devrik dizilim, üçleme, metafor, duraklama, hikâye yayı.
 *
 * Tek gerçek dilbilgisi kuralı ilk derste: bir tümleç öne alınınca çekimli
 * fiil ikinci sıraya geçer. Bunu B1'den beri biliyorsun; buradaki yenilik onu
 * ETKİ için bilerek kullanmak. "Ich habe selten so gelacht" düz bir cümledir,
 * "Selten habe ich so gelacht" bir vurgudur — aynı bilgi, iki ayrı ağırlık.
 *
 * Sahneler bilerek sahne: sunum, panel, doğaçlama, etkinlik sunuculuğu, veda
 * konuşması, münazara. C1'de öğrenci artık dinleyici karşısında.
 *
 * Adım dengesi: her derste 5 kelime tekrarı + 4 üretim + 1 doğru/yanlış.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

