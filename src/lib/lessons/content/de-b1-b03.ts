/**
 * B1 · Modül 3 — Bağlaç ustalığı (021–030). WP-71 pilotu.
 *
 * Modülün derdi tek: cümleleri BAĞLAMAK. A2 weil/dass'ı verdi; burada amaç
 * (damit / um…zu), zıtlık (obwohl / trotzdem), zaman (als / wenn / nachdem /
 * bevor / während), sonuç (deshalb) ve ikili bağlaçlar (je…desto,
 * entweder…oder) sırayla geliyor. Her dersin tek bir bağlacı var ve
 * karşıtıyla birlikte öğretiliyor (damit ↔ um…zu, als ↔ wenn), çünkü Türkçe
 * konuşanın hatası bağlacı bilmemek değil, ikisini karıştırmak.
 *
 * Adım dengesi (WP-71): tekrar ≤ %40, üret ≥ %30; her derste 4 üret + 1
 * doğru/yanlış. Kelimeler havuzdan; kalıplar konuşma fazına taşınıyor.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

/** Standart kelime adımı: "n. kelimemiz: X — anlamı; X deyin." */
function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

