import { de, tr, type Lesson, type LectureStep, type Segment } from "../types";

/**
 * B2 · Modül 10 — Resmî yazışma ve B2 kapanışı (091–100).
 *
 * Son modül iki iş yapıyor. Birincisi eksik kalan tek alanı kapatmak: resmî
 * yazışmanın sabit kalıpları (hitap, konu satırı, ek, kapanış). Bunlar
 * yaratıcılık istemiyor, ezber istiyor — ve tam da bu yüzden derste kalıp
 * olarak veriliyor, kurdurulmuyor.
 *
 * İkincisi seviyeyi TOPLAMAK. 094'ten itibaren dersler yeni bir kural
 * getirmiyor; B2 boyunca öğrenilenleri gerçek bir işin içinde yan yana
 * çalıştırıyor: mülakatta soru sormak (dolaylı soru), sunum kapatmak
 * (isimleşme), veda konuşması (Plusquamperfekt), referans yazmak (ortaç
 * sıfatları), tersine kültür şoku (als ob), C1 hazırlığı (öznel kipler).
 *
 * Kapanış dersi bilerek edilgen geçmişle yazıldı — B2'nin ilk modülünde
 * öğretilen yapı, seviyenin son cümlesinde geri dönüyor: "Vieles ist erreicht
 * worden."
 *
 * Adım dengesi: her derste 5 kelime tekrarı + 4 üretim + 1 doğru/yanlış.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

