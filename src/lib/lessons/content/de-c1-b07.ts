import { de, tr, type Lesson, type LectureStep, type Segment } from "../types";

/**
 * C1 · Modül 7 — Karmaşık yapılar (061–070).
 *
 * Bu modül iki yönde çalışıyor ve ikincisi çoğu kursta atlanıyor: SIKIŞTIRMAK
 * ve AÇMAK. Almanca yazı dili bir ilgi cümlesini ismin önüne katlayabiliyor
 * ("die vor Jahren getroffene Entscheidung"), üç cümleyi bir isim öbeğine
 * indirebiliyor, gereksiz gördüğünü tamamen atabiliyor ("Wie besprochen.").
 * C1 öğrencisinden beklenen bunları kurmak kadar ÇÖZMEK — çünkü sözleşme,
 * makale ve rapor bu dille yazılıyor.
 *
 * 063 bilerek bir yöntem dersi: uzun cümlede önce özneyi ve çekimli fiili
 * bulmak, sonra parçalara ayırmak. Kural değil teknik öğretiyor.
 *
 * 070 modülün tacı ve seviyenin en C1'lik dersi: `scheinbar` ile
 * `anscheinend` arasındaki fark. İkisi de Türkçeye "görünüşe göre" diye
 * çevrilir ama biri "öyle görünüyor ama değil", öteki "muhtemelen öyle"
 * demektir. Bu ayrımı bilmeyen biri kusursuz cümlelerle yanlış şey söyler.
 *
 * Adım dengesi: her derste 5 kelime tekrarı + 4 üretim + 1 doğru/yanlış.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

