/**
 * B2 · Modül 7 — Kültür ve sanat (061–070).
 *
 * Bu modülün dilbilgisel merkezi ilgi cümlesinin en son ve en zor hâli:
 * tamlayan hâlindeki ilgi zamiri (dessen / deren). B1'de "kitabı okuduğumuz
 * yazar" için iki cümle gerekiyordu; B2'de tek cümle yetiyor — ama zamirin
 * biçimi ÖNCEKİ ismin cinsine, çekimli fiil ise SONRAKİ ismin sayısına
 * bağlı. İki ayrı yere bakmak gerekiyor ve öğrenci genellikle birine bakıp
 * ötekini unutuyor; modülün doğru/yanlış maddeleri bilerek bu iki noktaya
 * ayrıldı.
 *
 * İkinci hat ince tanımlama: sanat konuşmak, bir şeyin nasıl olduğunu değil
 * SANA NE YAPTIĞINI anlatmayı gerektiriyor. Bu yüzden ortaç sıfatları,
 * yöntem bağlacı ve orantı bağlacı burada estetik yargı kurmak için
 * kullanılıyor.
 *
 * Adım dengesi: her derste 5 kelime tekrarı + 4 üretim + 1 doğru/yanlış.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

