import { de, tr, type Lesson, type LectureStep, type Segment } from "../types";

/**
 * B2 · Modül 8 — Para ve kariyer stratejisi (071–080).
 *
 * Bu modülün konusu tek bir dilbilgisi yapısı değil, bir DURUŞ: kendi
 * çıkarını savunurken makul kalmak. Almanca bunu üç araçla yapıyor ve üçü de
 * bu modülde yan yana çalışıyor — dilek kipi (talebi öneriye çevirir),
 * koşullu bağlaçlar (sözü bağlayıcı olmaktan çıkarır) ve isimleşmiş resmî
 * dil (kişiyi cümleden çıkarır).
 *
 * Türkçe konuşan için tuzak şurada: Türkçede maaş konuşurken kibarlık ekle
 * ve tonla kurulur ("şöyle düşünüyordum acaba"). Almancada aynı yumuşaklık
 * KİP ile kurulur ve tonu değiştirmeye gerek kalmaz — "Ich hätte mir …
 * vorgestellt" cümlesi düz sesle söylendiğinde bile bir teklif olarak
 * duyulur.
 *
 * Adım dengesi: her derste 5 kelime tekrarı + 4 üretim + 1 doğru/yanlış.
 */

const repeat = (target: string): LectureStep["expect"] => ({ kind: "repeat", target });
const produce = (target: string, hint: Segment[], accept?: string[]): LectureStep["expect"] => ({ kind: "produce", target, accept, hint });
const truefalse = (statement: string, answer: boolean, why: Segment[]): LectureStep["expect"] => ({ kind: "truefalse", statement, answer, why });

function word(n: string, w: { de: string; tr: string }, note?: string): LectureStep {
  return {
    say: [tr(`${n} kelimemiz:`), de(w.de), tr(`'${w.tr}' demek.${note ? ` ${note}` : ""} Lütfen`), de(w.de), tr("deyin.")],
    expect: repeat(w.de),
  };
}

